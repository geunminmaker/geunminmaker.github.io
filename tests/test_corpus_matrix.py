def _hwpx_available() -> bool:
    try:
        import splitcore.export.hwpx  # noqa: F401
        return True
    except ImportError:
        return False


@pytest.mark.parametrize("name,pick,rows,cols,fmt,paper,password", PARAMS)
def test_export_matrix(name, pick, rows, cols, fmt, paper, password):
    if fmt == "hwpx" and not _hwpx_available():
        pytest.skip("hwpx exporter not built yet")
    path = os.path.join(CORPUS, name)
    session = Session()
    try:
        with open(path, "rb") as handle:
            result = session.add_file(name, handle.read(), password)
        sid = result["sources"][pick]["id"]
        files = {f.name: f.data for f in session.export(sid, rows, cols, fmt, {"paper": paper})}
    finally:
        session.clear()
    problems = verify_outputs(path, files, rows=rows, cols=cols, fmt=fmt, paper=paper, pick=pick, password=password)
    assert not problems, problems


def test_expected_errors():
    with open(MANIFEST, encoding="utf-8") as handle:
        manifest = json.load(handle)
    for name, info in manifest.items():
        want = info.get("expect_error")
        if not want:
            continue
        with open(os.path.join(CORPUS, name), "rb") as handle:
            data = handle.read()
        with pytest.raises(SplitError) as err:
            Session().add_file(name, data)
        assert err.value.code == want, name


def test_every_good_file_opens_with_the_documented_number_of_pictures():
    with open(MANIFEST, encoding="utf-8") as handle:
        manifest = json.load(handle)
    for name, info in manifest.items():
        if info.get("expect_error"):
            continue
        session = Session()
        with open(os.path.join(CORPUS, name), "rb") as handle:
            result = session.add_file(name, handle.read(), info.get("password"))
        expected = info.get("pictures") or info.get("pages") or info.get("count") or 1
        assert len(result["sources"]) == expected, name
        if "size" in info:
            first = result["sources"][0]
            assert [first["width"], first["height"]] == info["size"], name
        session.clear()
